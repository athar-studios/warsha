import React from 'react';

export interface IconProps extends React.SVGAttributes<SVGSVGElement> {
  size?: number | string;
  label?: string;
  mirror?: boolean;
}

function createIcon(
  name: string,
  paths: React.ReactNode,
  directional = false
): React.FC<IconProps> {
  const Component: React.FC<IconProps> = ({
    size = 24,
    label,
    mirror,
    className = '',
    style,
    ...rest
  }) => {
    const shouldMirror = mirror ?? directional;
    const classes = [
      'w-icon',
      `w-icon-${name}`,
      shouldMirror ? 'w-icon--mirror' : '',
      className,
    ]
      .filter(Boolean)
      .join(' ');

    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="none"
        stroke="currentColor"
        strokeWidth="1.75"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={classes}
        style={style}
        aria-hidden={label ? undefined : true}
        role={label ? 'img' : undefined}
        aria-label={label}
        {...rest}
      >
        {paths}
      </svg>
    );
  };

  Component.displayName = `Icon${name.charAt(0).toUpperCase() + name.slice(1)}`;
  return Component;
}

